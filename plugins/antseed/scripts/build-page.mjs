import { readFile, writeFile } from 'node:fs/promises';

// Magpie's sandbox has an opaque origin. A classic bundle works in its
// desktop iframe and in the authenticated web UI's inline-assets path.
const base = new URL('../page/', import.meta.url);
const settings = (await readFile(new URL('settings.mjs', base), 'utf8')).replace(/^export (?=(?:const|function) )/gm, '');
const source = await readFile(new URL('app.source.mjs', base), 'utf8');
const importLine = "import { BOOL_FIELDS, PRICE_FIELDS, collectSettings } from './settings.mjs';";
if (!source.startsWith(importLine) || /^\s*(?:import|export)\s/m.test(settings)) throw new Error('Unexpected page module structure.');
const app = source.slice(importLine.length).trimStart();
if (/^\s*(?:import|export)\s/m.test(app)) throw new Error('Bundle new imports explicitly.');
const output = `// Generated by scripts/build-page.mjs. Edit app.source.mjs or settings.mjs.\n(async () => {\n'use strict';\n${settings}\n${app}\n})();\n`;
const target = new URL('app.js', base);
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Page bundle is stale. Run npm run build.');
} else {
  await writeFile(target, output);
}
